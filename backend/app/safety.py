"""Deterministic safety layer. Runs on every message BEFORE the LLM is called.

Plain Python pattern matching, no AI. That means:
  + it gives the same answer every time and can be unit-tested exactly
  + it still works if the LLM provider is down
  - it misses paraphrases that aren't in the lists (false negatives)
  - it fires on words used in a harmless context (false positives)
  - it only understands English
The LLM can raise a second, independent flag (tool: flag_urgent_symptoms) to
catch some of what these lists miss. Neither layer is clinically validated.

Three levels for physical symptoms, plus self-harm:
  EMERGENCY  - urgent symptoms that appear to be happening now -> stop, fixed template
  POSSIBLE   - urgent symptom words, but described as past or negated ->
               add a fixed "if this is happening now" line, then carry on
  NONE       - nothing matched
"""
import re
from enum import Enum


class Level(str, Enum):
    SELF_HARM = "self_harm"
    EMERGENCY = "emergency"
    POSSIBLE = "possible"
    NONE = "none"


SELF_HARM_PATTERNS = [
    r"\bkill (my ?self|myself)\b",
    r"\bend (my|his|her) life\b",
    r"\bsuicid(e|al)\b",
    r"\bwant to die\b",
    r"\b(don'?t|do not) want to (live|be alive)\b",
    r"\bhurt(ing)? myself\b",
    r"\bself[- ]?harm\b",
    r"\bno reason to live\b",
    r"\bbetter off dead\b",
]

EMERGENCY_PATTERNS = [
    r"\bchest (pain|pressure|tightness|heaviness)\b",
    r"\bpain in (my|his|her|the) chest\b",
    r"\bheart attack\b",
    r"\b(can'?t|cannot|can not|unable to|struggling to) breathe?\b",
    r"\b(difficulty|trouble|problem) breathing\b",
    r"\bbreathless(ness)?\b",
    r"\bshort(ness)? of breath\b",
    r"\bgasping\b",
    r"\b(lips?|face|fingers?) (look|looks|looking|are|is|turning|turned|gone|going)( a bit| slightly| very)? (blue|bluish|purple)\b",
    r"\bblue lips\b",
    r"\bunconscious\b",
    r"\b(not|isn'?t|is not) (responding|waking up|breathing)\b",
    r"\b(fainted|collapsed|passed out)\b",
    r"\b(seizures?|convulsions?|having (a )?fits?|fitting)\b",
    r"\bstroke\b",
    r"\b(face|mouth) (is )?droop(ing|y)?\b",
    r"\bslurred speech\b|\bspeech (is )?slurred\b",
    r"\b(one side|left side|right side|arm|leg) (is |has gone |went )?(numb|weak|paraly[sz]ed)\b",
    r"\b(heavy|severe|lot of|won'?t stop) bleeding\b|\bbleeding (heavily|a lot|won'?t stop)\b",
    r"\boverdose\b|\btook too many (pills|tablets)\b",
    r"\b(swallowed|drank) (poison|bleach|acid|pesticide)\b|\bpoison(ed|ing)\b",
    r"\b(severe|serious) (accident|burn|allergic reaction|head injury)\b",
    r"\b(throat|tongue) (is )?(swelling|swollen|closing)\b",
]

# Words that suggest the symptom is in the past or is being denied.
PAST_OR_NEGATED = [
    r"\blast (year|month|week)\b", r"\b\d+ (years?|months?|weeks?) ago\b",
    r"\byears ago\b", r"\bmonths ago\b", r"\bhistory of\b", r"\bin the past\b",
    r"\bpreviously\b", r"\bused to\b", r"\bhad (a )?(mild )?(chest|heart|stroke|seizure)",
    r"\bno (chest|breathing|bleeding)\b", r"\bnot having\b", r"\bwithout (any )?(chest|breathing)\b",
    r"\bfollow[- ]?up\b", r"\bafter (his|her|my) (heart attack|stroke)\b",
]

# Words that suggest it is happening now. These override PAST_OR_NEGATED.
HAPPENING_NOW = [
    r"\bright now\b", r"\bcurrently\b", r"\bat the moment\b",
    r"\bsince (this )?(morning|evening|last night|yesterday|an hour)\b", r"\bjust (started|now)\b",
    r"\b(is|am|are) having\b", r"\bagain\b",
]


def _normalise(text: str) -> str:
    text = text.lower().replace("’", "'").replace("‘", "'")
    return " ".join(text.split())


def _any(patterns: list[str], text: str) -> bool:
    return any(re.search(p, text) for p in patterns)


def classify(text: str) -> Level:
    t = _normalise(text)
    if _any(SELF_HARM_PATTERNS, t):
        return Level.SELF_HARM
    if _any(EMERGENCY_PATTERNS, t):
        if _any(PAST_OR_NEGATED, t) and not _any(HAPPENING_NOW, t):
            return Level.POSSIBLE
        return Level.EMERGENCY
    return Level.NONE


